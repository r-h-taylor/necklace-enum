"""Counting derivative structures by Burnside's lemma, without listing them.

This is an independent route to the numbers produced by ``count_structures``: it
shares the superlattice list and the symmetry operations with the generator, but
not the word picture or the generator kernel. Its cost grows with the number of
superlattices and symmetry operations, not with the number of structures, so it
reaches sizes far beyond any listing.

For one superlattice S with quotient group G = L/S, the derivative structures are
the orbits of *primitive* labelings (no nonzero translation of G fixes them) under

    Gamma_S = (translations G  x|  operations fixing S)  x  label exchanges.

Burnside's lemma gives

    #orbits = (1/|Gamma_S|) * sum over gamma in Gamma_S of #{primitive labelings fixed by gamma},

and primitivity is imposed by Moebius inversion on the lattice of subgroups of G:

    #{primitive, fixed by gamma} = sum over subgroups K of G of mu(0, K) * #{fixed by gamma, K-invariant}.

For a finite abelian group, mu(0, K) is nonzero only when every Sylow part of K is
elementary abelian, K = sum_p (Z_p)^r_p, and then mu(0, K) = prod_p (-1)^r_p p^(r_p(r_p-1)/2).
A labeling that is K-invariant and fixed by gamma is also invariant under the images
of K under gamma's linear part, so K is first closed under that action; the
labeling is then a labeling of the coset space, and the number fixed by gamma is a
product over the cycles of the induced permutation.

All arithmetic on counts uses Python integers, so there is no overflow.
"""
from __future__ import annotations

import itertools
from collections import Counter
from math import prod

import numpy as np
from numba import njit

from .core import _composition_vector, _label_group, _site_perm, _sizes, _stabilizer_ops
from .lattice import Quotient, unique_superlattices
from .parent import Parent


# ---------------------------------------------------------------- number theory
def _prime_factors(n):
    out, p = [], 2
    while p * p <= n:
        if n % p == 0:
            out.append(p)
            while n % p == 0:
                n //= p
        p += 1
    if n > 1:
        out.append(n)
    return out


# ---------------------------------------------------------------- subgroups of G
def _span(q: Quotient, gens):
    """Subgroup of G generated by the elements gens (indices), as a sorted tuple of indices."""
    elems = q.elems
    S = {int(q.index(np.zeros(3, dtype=np.int64)))}
    frontier = list(S)
    gvecs = [elems[g] for g in gens]
    while frontier:
        new = []
        for s in frontier:
            for v in gvecs:
                x = int(q.index(elems[s] + v))
                if x not in S:
                    S.add(x)
                    new.append(x)
        frontier = new
    return tuple(sorted(S))


def _moebius_subgroups(q: Quotient):
    """[(subgroup as tuple of element indices, mu(0, subgroup))] for the subgroups with
    nonzero Moebius value: products over primes p of elementary abelian p-subgroups."""
    d = q.d
    per_prime = []
    for p in _prime_factors(q.n):
        # G[p] = elements of order dividing p: spanned by (d_i / p) e_i for p | d_i
        basis = []
        for i in range(3):
            if d[i] % p == 0:
                v = np.zeros(3, dtype=np.int64)
                v[i] = d[i] // p
                basis.append(int(q.index(v)))
        socle = _span(q, basis)
        # every subspace of the F_p-vector space G[p], with its dimension
        subs = {}
        nonzero = [x for x in socle if q.elems[x].any()]
        for r in range(len(basis) + 1):
            for gens in itertools.combinations(nonzero, r):
                K = _span(q, gens)
                if len(K) == p ** r and K not in subs:
                    subs[K] = r
        per_prime.append([(K, (-1) ** r * p ** (r * (r - 1) // 2)) for K, r in subs.items()])
    out = []
    for combo in itertools.product(*per_prime):
        gens = [x for K, _ in combo for x in K]
        K = _span(q, gens) if gens else _span(q, [])
        out.append((K, prod(mu for _, mu in combo)))
    return out


def _closure(q: Quotient, K, T):
    """Smallest subgroup containing K that is invariant under g -> T g (mod D)."""
    gens = set(K)
    while True:
        imgs = {int(x) for x in q.index(q.elems[list(gens)] @ T.T)}
        if imgs <= gens:
            break
        gens = set(_span(q, sorted(gens | imgs)))
    return tuple(sorted(gens))


# ---------------------------------------------------------------- cycle types
@njit(cache=True)
def _cycle_types(base, tcos, nsite_cos, kind_class, nclass, out):
    """For each translation t (row of tcos), the permutation of the quotient sites
    (i, c) -> (base_kind[i,c], tcos[t, base_coset[i,c]]) is decomposed into cycles;
    out[t, L, cl] counts cycles of length L whose sites have allowed-class cl."""
    nt = tcos.shape[0]
    Nq = base.shape[0]
    seen = np.zeros(Nq, dtype=np.bool_)
    perm = np.empty(Nq, dtype=np.int64)
    for t in range(nt):
        for x in range(Nq):
            b = base[x]
            kind = b // nsite_cos
            c = b % nsite_cos
            perm[x] = kind * nsite_cos + tcos[t, c]
        seen[:] = False
        for x in range(Nq):
            if seen[x]:
                continue
            L = 0
            y = x
            while not seen[y]:
                seen[y] = True
                y = perm[y]
                L += 1
            out[t, L, kind_class[x]] += 1


# ---------------------------------------------------------------- fixed-point counts
class _Labels:
    """Per-cycle counts: a cycle of length L on sites of allowed-class cl, under label
    permutation eps, admits labels c with eps^L(c) = c, all of eps^i(c) allowed (and,
    for inclusion-exclusion, inside a species subset U)."""

    def __init__(self, P: Parent, LG, classes):
        self.k = P.k
        self.LG = [tuple(int(x) for x in e) for e in LG]
        self.classes = classes          # list of frozensets of allowed species
        self._cache = {}

    def orbit_seq(self, e, c, L):
        seq = [c]
        for _ in range(L - 1):
            seq.append(e[seq[-1]])
        return seq if e[seq[-1]] == c else None

    def count(self, e, L, cl, U):
        key = (e, L, cl, U)
        if key not in self._cache:
            A = self.classes[cl] & U
            n = 0
            for c in A:
                seq = self.orbit_seq(e, c, L)
                if seq is not None and all(s in A for s in seq):
                    n += 1
            self._cache[key] = n
        return self._cache[key]

    def poly(self, e, L, cl, w):
        """Generating polynomial {count vector: multiplicity} of the labels of one cycle
        whose sites each stand for w sites of the crystal."""
        key = ("poly", e, L, cl, w)
        if key not in self._cache:
            out = Counter()
            for c in self.classes[cl]:
                seq = self.orbit_seq(e, c, L)
                if seq is None or not all(s in self.classes[cl] for s in seq):
                    continue
                v = [0] * self.k
                for s in seq:
                    v[s] += w
                out[tuple(v)] += 1
            self._cache[key] = dict(out)
        return self._cache[key]


def _fixed_all(lab: _Labels, ctype, e, incomplete):
    """Labelings fixed by (cycle type, label permutation e), all compositions."""
    k = lab.k
    if incomplete:
        U = frozenset(range(k))
        return prod(lab.count(e, L, cl, U) ** m for (L, cl), m in ctype)
    total = 0
    for r in range(k + 1):                                   # inclusion-exclusion
        for U in itertools.combinations(range(k), r):
            U = frozenset(U)
            f = 1
            for (L, cl), m in ctype:
                c = lab.count(e, L, cl, U)
                if c == 0:
                    f = 0
                    break
                f *= c ** m
            total += (-1) ** (k - r) * f
    return total


def _fixed_comp(lab: _Labels, ctype, e, conc, w):
    """Labelings fixed by (cycle type, e) with exactly the composition conc; every
    quotient site stands for w sites."""
    conc = tuple(int(x) for x in conc)
    states = {tuple([0] * lab.k): 1}
    for (L, cl), m in ctype:
        terms = lab.poly(e, L, cl, w)
        for _ in range(m):
            new = Counter()
            for s, ways in states.items():
                for v, mult in terms.items():
                    t = tuple(a + b for a, b in zip(s, v))
                    if all(a <= b for a, b in zip(t, conc)):
                        new[t] += ways * mult
            states = new
            if not states:
                return 0
    return states.get(conc, 0)


# ---------------------------------------------------------------- driver
def _count_one(P: Parent, n, label_exchange, conc, include_incomplete):
    d = P.d
    LG = _label_group(P, label_exchange)
    if conc is not None:
        LG = [p for p in LG if all(conc[p[l]] == conc[l] for l in range(P.k))]
    classes = sorted(set(P.allowed), key=sorted)
    kind_cl = [classes.index(a) for a in P.allowed]
    lab = _Labels(P, LG, classes)
    total_num = 0
    for H in unique_superlattices(n, P.rots):
        q = Quotient(H)
        ops = _stabilizer_ops(P, H)
        order = q.n * len(ops) * len(LG)
        subgroups = _moebius_subgroups(q)
        acc = 0
        for op in ops:
            T = q.L @ op[0] @ q.Linv
            sp = _site_perm(P, q, op)                       # site i*n+g -> image
            for K0, mu in subgroups:
                K = _closure(q, K0, T)
                Kset = np.array(K)
                # coset id of every element: smallest index in g + K
                cid_raw = q.index(q.elems[:, None, :] + q.elems[Kset][None, :, :]).min(1)
                reps, cid = np.unique(cid_raw, return_inverse=True)
                nc = len(reps)
                # translations by coset representatives act on cosets
                tcos = cid[q.index(q.elems[reps][:, None, :] + q.elems[reps][None, :, :])]
                tcos = tcos.T.copy()                        # tcos[t, c] = coset of rep_c + rep_t
                # op acting on quotient sites (i, coset)
                base = np.empty(d * nc, dtype=np.int64)
                kind_class = np.empty(d * nc, dtype=np.int64)
                for i in range(d):
                    for ci, g in enumerate(reps):
                        img = sp[i * q.n + g]
                        base[i * nc + ci] = (img // q.n) * nc + cid[img % q.n]
                        kind_class[i * nc + ci] = kind_cl[i]
                hist = np.zeros((nc, d * nc + 1, len(classes)), dtype=np.int64)
                _cycle_types(base, tcos, nc, kind_class, len(classes), hist)
                # each coset translation stands for |K| translations of G
                types = Counter()
                for t in range(nc):
                    nz = np.argwhere(hist[t])
                    types[tuple((int(L), int(c), int(hist[t, L, c])) for L, c in nz)] += 1
                for ct, mult in types.items():
                    ctype = [((L, c), m) for L, c, m in ct]
                    for e in lab.LG:
                        if conc is not None:
                            f = _fixed_comp(lab, ctype, e, conc, len(K))
                        else:
                            f = _fixed_all(lab, ctype, e, include_incomplete)
                        acc += mu * mult * len(K) * f
        if acc % order:
            raise ArithmeticError(f"Burnside sum not divisible by group order for H={H.tolist()}")
        total_num += acc // order
    return total_num


def count_structures_burnside(parent: Parent, sizes, composition=None, label_exchange=False,
                              include_incomplete=False):
    """Number of derivative structures for each size, by Burnside's lemma.

    Same arguments and conventions as :func:`count_structures`, and the same
    results, but computed without generating any structure. Returns {n: count}.
    """
    out = {}
    for n in _sizes(sizes):
        conc = None
        if composition is not None:
            conc = _composition_vector(parent, composition, n * parent.d)
            if conc is None:
                out[n] = 0
                continue
        out[n] = _count_one(parent, n, label_exchange, conc, include_incomplete)
    return out
